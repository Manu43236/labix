CREATE TABLE results (
    id              VARCHAR(36)     NOT NULL,
    visit_test_id   VARCHAR(36)     NOT NULL,
    parameter_id    VARCHAR(36)     NOT NULL,
    value_text      VARCHAR(500),
    value_number    DOUBLE,
    unit            VARCHAR(30),
    range_low       DOUBLE,
    range_high      DOUBLE,
    critical_low    DOUBLE,
    critical_high   DOUBLE,
    range_text      VARCHAR(100),
    flag            VARCHAR(10),
    range_edited    TINYINT(1)   NOT NULL DEFAULT 0,
    entered_by      VARCHAR(36),
    entered_at      DATETIME(6),
    created_at      DATETIME(6),
    updated_at      DATETIME(6),
    created_by      VARCHAR(36),
    updated_by      VARCHAR(36),
    PRIMARY KEY (id),
    UNIQUE KEY uk_result_param (visit_test_id, parameter_id),
    INDEX idx_result_visit_test (visit_test_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
